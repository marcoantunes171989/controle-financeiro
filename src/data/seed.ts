const hoje = new Date();
const mes = (offset: number) => {
  const d = new Date(hoje.getFullYear(), hoje.getMonth() + offset, 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
};
